def technique(tid):
    name, tactic = ATTACK.get(tid, ATTACK.get(tid.split(".")[0], ("", "")))
    return {"id": tid, "name": name, "tactic": tactic, "url": "https://attack.mitre.org/techniques/" + tid.replace(".", "/")}


def R(rid, name, category, severity, confidence, method, mitre, telemetry, fp, limitation="", threshold=None,
      required=None, description="", impact="", recommendation=""):
    return rid, {"id": rid, "name": name, "category": category, "severity": severity, "confidence": confidence,
                 "method": method, "mitre": mitre, "telemetry": telemetry, "fp": fp, "limitation": limitation,
                 "threshold": threshold or {}, "required_fields": required or [], "enabled": True,
                 "description": description, "impact": impact, "recommendation": recommendation}


